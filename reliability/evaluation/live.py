"""Live regression and model metamorphic relations (phase 7).

Live models are nondeterministic, so a single run proves little. Both procedures here use
repeated runs and compare rates, never single verdicts.

Live regression
    Each scenario runs N times (default 5). For every (scenario, check) the pass rate is
    PASS / (PASS + FAIL); ERROR and INCONCLUSIVE are counted separately. A check regresses
    when its pass rate drops by more than `regression_margin` below the stored baseline.
    The record keeps model, per-scenario prompt hashes and a config hash, so a comparison
    across changed prompts is flagged rather than silently accepted.

Model metamorphic relations
    For selected scenarios, variants are built from annotations, never generated by a model:
    hand-written paraphrases of the question, reversed document order, and an added
    irrelevant document. Each variant runs `metamorphic_runs` times; consistency is the
    share of variant verdicts equal to the original's majority verdict, per check.
    Retrieval-side checks (`retrieval_metrics`, `context_quality`) are excluded because the
    variants change retrieval by construction. Inconsistency is a finding about the model,
    not a failure of this project.
"""

from __future__ import annotations

import hashlib
import json
import time
from collections import Counter
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from reliability.config import AppConfig
from reliability.errors import ConfigError
from reliability.evaluation.orchestration import build_request, call_with_retries, make_evaluator
from reliability.models import Document, Message, RetrievedRef, Scenario, Status
from reliability.providers.base import Provider
from reliability.providers.prompting import prompt_hash
from reliability.reporting.redaction import Redactor

Sleep = Callable[[float], None]
RETRIEVAL_SIDE_CHECKS = frozenset({"retrieval_metrics", "context_quality"})


def config_hash(config: AppConfig) -> str:
    payload = json.dumps(config.model_dump(mode="json"), sort_keys=True)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


@dataclass
class RateCounts:
    passed: int = 0
    failed: int = 0
    other: Counter[str] = field(default_factory=Counter)

    def add(self, status: Status) -> None:
        if status is Status.PASS:
            self.passed += 1
        elif status is Status.FAIL:
            self.failed += 1
        else:
            self.other[status.value] += 1

    @property
    def pass_rate(self) -> float | None:
        decided = self.passed + self.failed
        return round(self.passed / decided, 4) if decided else None


def _evaluate_once(
    scenario: Scenario,
    *,
    provider: Provider,
    documents: Mapping[str, Document],
    config: AppConfig,
    redactor: Redactor,
    sleep: Sleep,
) -> dict[str, Status]:
    evaluator = make_evaluator(config, documents, redactor)
    request = build_request(scenario, documents, config)
    outcome = call_with_retries(provider, request, config.limits, sleep)
    return {c.check: c.status for c in evaluator.evaluate(scenario, outcome).checks}


# --------------------------------------------------------------------------- live regression


def repeated_run(
    *,
    scenarios: Sequence[Scenario],
    provider: Provider,
    documents: Mapping[str, Document],
    config: AppConfig,
    redactor: Redactor,
    runs: int,
    sleep: Sleep = time.sleep,
) -> dict[str, Any]:
    rates: dict[str, dict[str, RateCounts]] = {}
    hashes: dict[str, str] = {}
    for scenario in scenarios:
        hashes[scenario.id] = prompt_hash(build_request(scenario, documents, config))
        per_check: dict[str, RateCounts] = {}
        for _ in range(runs):
            for check, status in _evaluate_once(
                scenario,
                provider=provider,
                documents=documents,
                config=config,
                redactor=redactor,
                sleep=sleep,
            ).items():
                per_check.setdefault(check, RateCounts()).add(status)
        rates[scenario.id] = per_check
    return {
        "record_schema": "1.0",
        "provider": provider.name,
        "model": provider.model,
        "runs": runs,
        "config_hash": config_hash(config),
        "prompt_hashes": hashes,
        "rates": {
            sid: {
                check: {
                    "pass_rate": counts.pass_rate,
                    "passed": counts.passed,
                    "failed": counts.failed,
                    "other": dict(sorted(counts.other.items())),
                }
                for check, counts in sorted(checks.items())
            }
            for sid, checks in sorted(rates.items())
        },
    }


@dataclass(frozen=True)
class LiveRegression:
    scenario_id: str
    check: str
    baseline: float
    current: float | None


def compare_live(
    baseline: Mapping[str, Any], current: Mapping[str, Any], margin: float
) -> tuple[list[LiveRegression], list[str]]:
    """Regressions beyond `margin`, plus warnings about records that are not comparable."""
    warnings: list[str] = []
    if baseline.get("model") != current.get("model"):
        warnings.append(f"model changed: {baseline.get('model')} -> {current.get('model')}")
    if baseline.get("config_hash") != current.get("config_hash"):
        warnings.append("configuration changed since the baseline")
    base_hashes: dict[str, str] = baseline.get("prompt_hashes", {})
    cur_hashes: dict[str, str] = current.get("prompt_hashes", {})
    for sid in sorted(base_hashes.keys() & cur_hashes.keys()):
        if base_hashes[sid] != cur_hashes[sid]:
            warnings.append(f"{sid}: prompt changed since the baseline")
    regressions: list[LiveRegression] = []
    base_rates: dict[str, dict[str, Any]] = baseline.get("rates", {})
    cur_rates: dict[str, dict[str, Any]] = current.get("rates", {})
    for sid, checks in sorted(base_rates.items()):
        if sid not in cur_rates:
            warnings.append(f"{sid}: missing from the current run")
            continue
        for check, values in sorted(checks.items()):
            before = values.get("pass_rate")
            after = cur_rates[sid].get(check, {}).get("pass_rate")
            if before is None:
                continue
            if after is None or after < before - margin:
                regressions.append(LiveRegression(sid, check, before, after))
    return regressions, warnings


def render_live(
    record: Mapping[str, Any],
    regressions: Sequence[LiveRegression] | None = None,
    warnings: Sequence[str] = (),
    margin: float | None = None,
) -> str:
    lines = [
        f"Live regression: provider {record['provider']} model {record['model']}, "
        f"{record['runs']} runs per scenario",
        "",
        "Pass rate per check (PASS / (PASS + FAIL); other statuses counted separately):",
    ]
    for sid, checks in record["rates"].items():
        cells = []
        for check, v in checks.items():
            rate = "n/a" if v["pass_rate"] is None else f"{v['pass_rate']:.0%}"
            other = "".join(f" {k}:{n}" for k, n in v["other"].items())
            cells.append(f"{check} {rate}{other}")
        lines.append(f"  {sid}: " + " | ".join(cells))
    if regressions is not None:
        lines += ["", f"Compared with baseline (margin {margin}):"]
        lines += [f"  ! warning: {w}" for w in warnings]
        lines += [
            f"  REGRESSION {r.scenario_id}/{r.check}: {r.baseline:.0%} -> "
            + ("n/a" if r.current is None else f"{r.current:.0%}")
            for r in regressions
        ] or ["  no regression beyond the margin"]
    return "\n".join(lines) + "\n"


def load_record(path: Path) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise ConfigError(f"baseline not found: {path}") from exc
    except ValueError as exc:
        raise ConfigError(f"baseline {path} is not valid JSON") from exc
    if not isinstance(data, dict) or data.get("record_schema") != "1.0" or "rates" not in data:
        raise ConfigError(f"{path} is not a live-regression record")
    return data


# --------------------------------------------------------------------------- model metamorphic


def variants(scenario: Scenario, irrelevant_doc: str) -> dict[str, Scenario]:
    out: dict[str, Scenario] = {}
    history = list(scenario.input.messages[:-1])
    for i, text in enumerate(scenario.paraphrases, start=1):
        new_input = scenario.input.model_copy(
            update={"messages": [*history, Message(role="user", content=text)]}
        )
        out[f"paraphrase-{i}"] = scenario.model_copy(update={"input": new_input})
    if len({r.doc_id for r in scenario.retrieved}) >= 2:
        top = max(r.rank for r in scenario.retrieved)
        reversed_refs = [
            RetrievedRef(doc_id=r.doc_id, rank=top + 1 - r.rank) for r in scenario.retrieved
        ]
        out["reversed-documents"] = scenario.model_copy(update={"retrieved": reversed_refs})
    if scenario.retrieved and irrelevant_doc not in {r.doc_id for r in scenario.retrieved}:
        last = max(r.rank for r in scenario.retrieved)
        extra = [*scenario.retrieved, RetrievedRef(doc_id=irrelevant_doc, rank=last + 1)]
        out["irrelevant-document"] = scenario.model_copy(update={"retrieved": extra})
    return out


def model_metamorphic(
    *,
    scenarios: Sequence[Scenario],
    provider: Provider,
    documents: Mapping[str, Document],
    config: AppConfig,
    redactor: Redactor,
    sleep: Sleep = time.sleep,
) -> dict[str, Any]:
    runs = config.live.metamorphic_runs
    irrelevant = config.live.metamorphic_irrelevant_doc
    if irrelevant not in documents:
        raise ConfigError(f"metamorphic_irrelevant_doc '{irrelevant}' is not in the dataset")
    results: dict[str, Any] = {}
    for scenario in scenarios:
        built = variants(scenario, irrelevant)
        if not built:
            continue

        def statuses(target: Scenario) -> list[dict[str, Status]]:
            return [
                {
                    k: v
                    for k, v in _evaluate_once(
                        target,
                        provider=provider,
                        documents=documents,
                        config=config,
                        redactor=redactor,
                        sleep=sleep,
                    ).items()
                    if k not in RETRIEVAL_SIDE_CHECKS
                }
                for _ in range(runs)
            ]

        original = statuses(scenario)
        checks = sorted({c for run in original for c in run})
        reference = {
            c: Counter(run[c] for run in original if c in run).most_common(1)[0][0] for c in checks
        }
        per_variant: dict[str, float | None] = {}
        agree = total = 0
        for name, variant in built.items():
            v_agree = v_total = 0
            for run in statuses(variant):
                for check in checks:
                    if check in run:
                        v_total += 1
                        v_agree += run[check] is reference[check]
            per_variant[name] = round(v_agree / v_total, 4) if v_total else None
            agree += v_agree
            total += v_total
        results[scenario.id] = {
            "reference": {c: s.value for c, s in reference.items()},
            "variants": per_variant,
            "consistency": round(agree / total, 4) if total else None,
        }
    return {
        "provider": provider.name,
        "model": provider.model,
        "runs_per_variant": runs,
        "excluded_checks": sorted(RETRIEVAL_SIDE_CHECKS),
        "scenarios": results,
    }


def render_metamorphic(result: Mapping[str, Any]) -> str:
    lines = [
        f"Model metamorphic relations: provider {result['provider']} model {result['model']}, "
        f"{result['runs_per_variant']} runs per variant "
        f"(excluded: {', '.join(result['excluded_checks'])})",
        "",
    ]
    for sid, data in result["scenarios"].items():
        consistency = data["consistency"]
        head = "n/a" if consistency is None else f"{consistency:.0%}"
        detail = ", ".join(
            f"{name} {'n/a' if v is None else f'{v:.0%}'}" for name, v in data["variants"].items()
        )
        lines.append(f"  {sid}: consistency {head} ({detail})")
    if not result["scenarios"]:
        lines.append("  no scenario has variants (add `paraphrases` or retrieved documents)")
    lines += ["", "Inconsistency is a finding about the model, not a test failure."]
    return "\n".join(lines) + "\n"
